// 输入毫秒时间戳，返回旅行者1号到地球的几何距离（千米）
function vgDist(ms) {
  var jd = ms / 86400000 + 2440587.5 + 69.184 / 86400; // UTC → TDB
  var x = 2 * (jd - vgT0) / (vgT1 - vgT0) - 1;
  x = x < -1 ? -1 : x > 1 ? 1 : x;                      // 窗口外钳位
  var T = [1, x];
  for (var k = 2; k <= 46; k++) T[k] = 2 * x * T[k - 1] - T[k - 2];
  var dt = jd - vgT0, L = vgNA * dt, W = vgNM * dt;
  var B = [T[0], T[1]];
  for (var i = 1; i <= 4; i++) { var c = Math.cos(i * L), s = Math.sin(i * L); B.push(T[0] * c, T[0] * s, T[1] * c, T[1] * s); }
  for (var j = 1; j <= 2; j++) { var c2 = Math.cos(j * W), s2 = Math.sin(j * W); B.push(T[0] * c2, T[0] * s2, T[1] * c2, T[1] * s2); }
  var d2 = 0;
  for (var a = 0; a < 3; a++) {
    var pv = vgV[a][0] + vgV[a][1] * dt, pe = 0;
    for (var i = 2; i < 47; i++) pv += vgV[a][i] * T[i];
    for (var i = 0; i < 26; i++) pe += vgE[a][i] * B[i];
    d2 += (pv - pe) * (pv - pe);
  }
  return Math.sqrt(d2);
}
function vgFmt(km) { return String(Math.round(km)).replace(/\B(?=(\d{3})+(?!\d))/g, ","); }
function vgLight(km) {
  var h = km / vgCKM / 3600, hour = Math.floor(h), min = Math.round((h - hour) * 60);
  if (min === 60) { min = 0; hour++; }
  return hour + " 小时 " + min + " 分";
}
